import "https://deno.land/x/xhr@0.1.0/mod.ts";
import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { name, profession, birthdate, birthplace, country, knownFor } = await req.json();
    
    const LOVABLE_API_KEY = Deno.env.get('LOVABLE_API_KEY');
    if (!LOVABLE_API_KEY) {
      throw new Error('LOVABLE_API_KEY not configured');
    }

    const prompt = `Write a comprehensive, SEO-friendly celebrity biography for ${name}, a ${profession} born on ${birthdate} in ${birthplace}, ${country}. ${knownFor ? `Known for: ${knownFor}.` : ''}

Requirements:
- Write at least 700 words
- Use factual, encyclopedia-style tone similar to entertainment biography sites
- Include sections: Early Life, Career Beginnings, Rise to Fame, Major Achievements, Personal Life, Trivia/Fun Facts
- Make it engaging and informative
- Use third person
- Include specific dates, achievements, and milestones where relevant
- Make it suitable for all audiences (family-friendly)
- Optimize for SEO with natural keyword integration

Format the response in HTML with proper headings (<h2>, <h3>) and paragraphs (<p>).`;

    const response = await fetch('https://ai.gateway.lovable.dev/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${LOVABLE_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'google/gemini-2.5-flash',
        messages: [
          { 
            role: 'system', 
            content: 'You are an expert celebrity biographer who writes comprehensive, SEO-optimized biographies for entertainment websites. Your writing is factual, engaging, and suitable for all audiences.'
          },
          { role: 'user', content: prompt }
        ],
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: 'Rate limit exceeded. Please try again later.' }),
          { status: 429, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: 'Payment required. Please add credits to your Lovable AI workspace.' }),
          { status: 402, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      const errorText = await response.text();
      console.error('AI Gateway error:', response.status, errorText);
      throw new Error(`AI Gateway error: ${response.status}`);
    }

    const data = await response.json();
    const biography = data.choices[0].message.content;

    return new Response(
      JSON.stringify({ 
        success: true,
        biography,
        wordCount: biography.split(/\s+/).length
      }),
      { 
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        status: 200 
      }
    );

  } catch (error) {
    console.error('Error generating biography:', error);
    return new Response(
      JSON.stringify({ 
        error: error instanceof Error ? error.message : 'Unknown error',
        success: false 
      }),
      { 
        status: 500,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' }
      }
    );
  }
});
